#ifndef PRINTER_SERVICE_GEOMETRY_H
#define PRINTER_SERVICE_GEOMETRY_H
/* V25: reduce both V24 single strokes by187 pulses (~1mm total).
 * Print10473, service11221; keep374 pulses (~2mm) inset at either end. */
#define PRINTER_SERVICE_BASE_STEPS 7480U
#define PRINTER_TRAVEL_REDUCTION_STEPS 187U
#define PRINTER_SERVICE_SPAN_STEPS (PRINTER_SERVICE_BASE_STEPS+3180U-PRINTER_TRAVEL_REDUCTION_STEPS)
#define PRINTER_SERVICE_MARGIN_STEPS ((PRINTER_SERVICE_SPAN_STEPS-PRINTER_SERVICE_BASE_STEPS)/2U)
#define PRINTER_SERVICE_RIGHT_MARGIN_STEPS (PRINTER_SERVICE_SPAN_STEPS-PRINTER_SERVICE_BASE_STEPS-PRINTER_SERVICE_MARGIN_STEPS)
#define PRINTER_PRINT_ENDPOINT_INSET_STEPS 374U
#define PRINTER_OC3_REFERENCE_STEPS (PRINTER_SERVICE_SPAN_STEPS+PRINTER_PRINT_ENDPOINT_INSET_STEPS)
#define PRINTER_MAINTENANCE_SPAN_STEPS (PRINTER_SERVICE_SPAN_STEPS+2U*PRINTER_PRINT_ENDPOINT_INSET_STEPS)
#define PRINTER_OC3_BOOT_SEARCH_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_OC3_BOOT_RETURN_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_OC3_PREP_SEARCH_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_OC3_PREP_RETURN_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_OC3_FINAL_RETURN_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_OC3_TRAVEL_LIMIT_STEPS PRINTER_MAINTENANCE_SPAN_STEPS
#define PRINTER_MAINTENANCE_EXTRA_STEPS PRINTER_PRINT_ENDPOINT_INSET_STEPS
/* Only the head-OFF service trial uses these speed parameters. */
#define PRINTER_SERVICE_START_LOW_US 3000U
#define PRINTER_SERVICE_CRUISE_LOW_US 600U
#define PRINTER_SERVICE_RAMP_STEPS 250U
#endif
